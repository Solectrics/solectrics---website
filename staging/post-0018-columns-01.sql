actual_columns(table_name,column_name,column_type,notnull_flag,default_value,pk) AS (
 SELECT s.name,p.name,upper(coalesce(p.type,'')),p."notnull",p.dflt_value,p.pk
 FROM sqlite_schema AS s JOIN pragma_table_info(s.name) AS p
 WHERE s.type='table' AND s.sql IS NOT NULL
  AND s.name NOT LIKE 'sqlite_%' AND substr(s.name,1,4)<>'_cf_' AND s.name<>'d1_migrations'
)
SELECT 'JOBHUB_VERIFY_OK:columns-01' AS result
WHERE NOT EXISTS(SELECT 1 FROM expected_columns e WHERE NOT EXISTS(
 SELECT 1 FROM actual_columns a WHERE a.table_name=e.table_name AND a.column_name=e.column_name
  AND upper(a.column_type)=e.column_type AND a.notnull_flag=e.notnull_flag
  AND a.default_value IS e.default_value AND a.pk=e.pk
))
UNION ALL
SELECT 'MISSING_OR_MISMATCHED_COLUMN:'||e.table_name||'.'||e.column_name
FROM expected_columns e WHERE NOT EXISTS(
 SELECT 1 FROM actual_columns a WHERE a.table_name=e.table_name AND a.column_name=e.column_name
  AND upper(a.column_type)=e.column_type AND a.notnull_flag=e.notnull_flag
  AND a.default_value IS e.default_value AND a.pk=e.pk
);

